#[test]
fn constructs_without_a_rule_are_refused_with_their_path() {
    let cases = [
        (
            json!({"type": "object", "properties": {"a": {"type": "string", "pattern": "x"}}}),
            "/schemas/Thing/properties/a: no rule for key \"pattern\"",
        ),
        (
            json!({"type": "object", "required": ["a"],
                   "properties": {"a": {"type": "number", "minimum": 0}}}),
            "a bound on a number",
        ),
        (
            json!({"type": "object", "properties": {"a": {"type": "string", "minLength": 1}}}),
            "a bound on an optional field",
        ),
        (
            json!({"type": "object", "required": ["a"],
                   "properties": {"a": {"type": ["string", "null"]}}}),
            "required and nullable without x-rtvbp-presence",
        ),
        (
            json!({"type": "object", "properties": {"a": {"type": "object",
                   "properties": {"b": {"type": "string"}}}}}),
            "/schemas/Thing/properties/a: no rule for key \"properties\"",
        ),
        (
            json!({"type": "object", "properties": {"a": {"type": "object"}}}),
            "inline object with properties",
        ),
        (
            json!({"type": "object", "properties": {"a": {"anyOf": [
                {"type": "string"}, {"type": "integer"}]}}}),
            "anyOf other than [$ref, null]",
        ),
        (
            json!({"type": "object", "properties": {"a": {"type": "array",
                   "items": {"type": ["string", "null"]}}}}),
            "nullable items",
        ),
        (
            json!({"type": "object", "required": ["b"], "properties": {"a": {"type": "string"}}}),
            "required but not declared",
        ),
        (
            json!({"type": "object", "additionalProperties": false}),
            "a closed object without properties",
        ),
        (
            json!({"type": "string"}),
            "a top-level schema that is not an object",
        ),
    ];
    for (schema, expected) in cases {
        let message = refusal(schema.clone());
        assert!(message.contains(expected), "{schema}: {message}");
    }
}

#[test]
fn an_unknown_role_or_format_version_is_refused() {
    let mut manifest = minimal_manifest(json!({"type": "object"}));
    manifest["operations"][0]["handledBy"] = json!("broker");
    let message = render_ess_domain(&manifest, "rtvbp.test_v1")
        .unwrap_err()
        .to_string();
    assert!(
        message.contains("operation thing.do: handledBy \"broker\""),
        "{message}"
    );

    let mut manifest = minimal_manifest(json!({"type": "object"}));
    manifest["formatVersion"] = json!(2);
    let message = render_ess_domain(&manifest, "rtvbp.test_v1")
        .unwrap_err()
        .to_string();
    assert!(message.contains("formatVersion 2"), "{message}");
}

#[test]
fn a_wire_name_without_a_variant_rule_is_refused() {
    for wire in [
        "audio.buffer-clear",
        "Session.set",
        "SessionSet",
        "session.Set",
        "session_set",
        "a..b",
        ".ping",
        "ping.",
        "2fa.start",
        "",
    ] {
        let message = ess_variant(wire).unwrap_err().to_string();
        assert!(message.contains("no variant rule"), "{wire:?}: {message}");

        let mut manifest = minimal_manifest(json!({"type": "object"}));
        manifest["operations"][0]["method"] = json!(wire);
        let message = render_ess_domain(&manifest, "rtvbp.test_v1")
            .unwrap_err()
            .to_string();
        assert!(message.contains("no variant rule"), "{wire:?}: {message}");

        let mut manifest = minimal_manifest(json!({"type": "object"}));
        manifest["events"] = json!([{
            "name": wire,
            "emittedBy": "voice",
            "description": "Seen.",
            "data": {"$ref": "#/schemas/Thing"},
        }]);
        let message = render_ess_domain(&manifest, "rtvbp.test_v1")
            .unwrap_err()
            .to_string();
        assert!(message.contains("no variant rule"), "{wire:?}: {message}");
    }
}

#[test]
fn two_wire_names_mapping_to_one_variant_are_refused() {
    let mut manifest = minimal_manifest(json!({"type": "object"}));
    let second = manifest["operations"][0].clone();
    manifest["operations"].as_array_mut().unwrap().push(second);
    let message = render_ess_domain(&manifest, "rtvbp.test_v1")
        .unwrap_err()
        .to_string();
    assert!(
        message.contains(
            "Method: wire names \"thing.do\" and \"thing.do\" both map to variant ThingDo"
        ),
        "{message}"
    );

    let event = |name: &str| {
        json!({
            "name": name,
            "emittedBy": "voice",
            "description": "Seen.",
            "data": {"$ref": "#/schemas/Thing"},
        })
    };
    let mut manifest = minimal_manifest(json!({"type": "object"}));
    manifest["events"] = json!([event("thing.seen"), event("thing.seen")]);
    let message = render_ess_domain(&manifest, "rtvbp.test_v1")
        .unwrap_err()
        .to_string();
    assert!(
        message.contains(
            "Event: wire names \"thing.seen\" and \"thing.seen\" both map to variant ThingSeen"
        ),
        "{message}"
    );

    let mut manifest = minimal_manifest(json!({"type": "object"}));
    manifest["events"] = json!([event("thing.do")]);
    assert!(
        render_ess_domain(&manifest, "rtvbp.test_v1").is_ok(),
        "a method and an event may share a wire name: they are separate enums"
    );
}
