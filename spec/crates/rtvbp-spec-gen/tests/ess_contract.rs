use std::path::Path;
use std::str::FromStr;

use rtvbp_spec_gen::emit::{
    ESS_REQUIREMENT, Target, ess_domain, ess_domain_path, ess_variant, render_ess_domain,
};
use rtvbp_spec_gen::generate;
use serde_json::{Value, json};

const DOMAIN: &str = "rtvbp.babelforce_v1";

fn ess_file(name: &str) -> String {
    let files = generate(Target::Ess).unwrap();
    let file = files
        .iter()
        .find(|file| file.path == Path::new(name))
        .unwrap_or_else(|| panic!("no generated {name}"));
    String::from_utf8(file.bytes.clone()).unwrap()
}

fn babelforce_manifest() -> Value {
    let files = generate(Target::Manifest).unwrap();
    let file = files
        .iter()
        .find(|file| file.path == Path::new("babelforce.v1.catalog.json"))
        .unwrap();
    serde_json::from_slice(&file.bytes).unwrap()
}

fn minimal_manifest(schema: Value) -> Value {
    json!({
        "formatVersion": 1,
        "catalog": {"id": "test.v1"},
        "operations": [{
            "method": "thing.do",
            "handledBy": "voice",
            "terminal": false,
            "description": "Do the thing.",
            "request": {"$ref": "#/schemas/Thing"},
            "response": {"$ref": "#/schemas/Thing"},
        }],
        "events": [],
        "schemas": {"Thing": schema},
    })
}

fn refusal(schema: Value) -> String {
    render_ess_domain(&minimal_manifest(schema), "rtvbp.test_v1")
        .unwrap_err()
        .to_string()
}

#[test]
fn ess_target_pins_its_output_tree() {
    assert_eq!(Target::from_str("ess").unwrap(), Target::Ess);
    assert!(Target::ALL.contains(&Target::Ess));
    assert_eq!(Target::Ess.canonical_out_dir(), "spec/ess");
    for owned in [
        "system.yaml",
        "components.yaml",
        "ess-inputs.yaml",
        "domains/babelforce-v1.yaml",
    ] {
        assert!(Target::Ess.owns_output_path(Path::new(owned)), "{owned}");
    }
    for foreign in [
        "README.md",
        "scenarios/a.yaml",
        "domains/notes.md",
        "x/system.yaml",
    ] {
        assert!(
            !Target::Ess.owns_output_path(Path::new(foreign)),
            "{foreign}"
        );
    }
    assert_eq!(ess_domain("babelforce.v1"), DOMAIN);
    assert_eq!(
        ess_domain_path("babelforce.v1"),
        Path::new("domains/babelforce-v1.yaml")
    );
}

#[test]
fn ess_emitter_writes_the_four_files_deterministically() {
    let first = generate(Target::Ess).unwrap();
    let second = generate(Target::Ess).unwrap();
    assert_eq!(first, second);
    let paths = first
        .iter()
        .map(|file| file.path.to_str().unwrap())
        .collect::<Vec<_>>();
    assert_eq!(
        paths,
        [
            "components.yaml",
            "domains/babelforce-v1.yaml",
            "ess-inputs.yaml",
            "system.yaml"
        ]
    );
    assert!(first.iter().all(|file| file.bytes.ends_with(b"\n")));
    assert!(first.iter().all(|file| !file.bytes.ends_with(b"\n\n")));
}

#[test]
fn ess_system_files_pin_the_release_and_carry_no_comments() {
    let inputs = ess_file("ess-inputs.yaml");
    assert!(inputs.starts_with("format: ess-inputs/2\n"));
    assert!(inputs.contains(&format!("requires: {ESS_REQUIREMENT}\n")));
    assert_eq!(ESS_REQUIREMENT, "ess 0.68.0");
    assert!(inputs.contains("  - domains/babelforce-v1.yaml\n"));
    let system = ess_file("system.yaml");
    assert!(system.contains("system: rtvbp\n"));
    assert!(system.contains(&format!("  - {DOMAIN}\n")));
    let components = ess_file("components.yaml");
    assert!(components.contains(&format!("      domains: [{DOMAIN}]\n")));
    for text in [inputs, system, components] {
        assert!(text.lines().all(|line| !line.trim_start().starts_with('#')));
    }
}

#[test]
fn ess_domain_is_a_function_of_the_published_manifest() {
    let domain = ess_file("domains/babelforce-v1.yaml");
    assert_eq!(
        render_ess_domain(&babelforce_manifest(), DOMAIN).unwrap(),
        domain
    );
    assert!(
        domain.starts_with(
            "# Code generated by rtvbp-spec-gen from the typed catalog. DO NOT EDIT.\n"
        )
    );
    assert!(domain.contains(&format!("\ndomain: {DOMAIN}\n")));
}

#[test]
fn every_schema_becomes_one_type_beside_the_role_method_and_event_enums() {
    let manifest = babelforce_manifest();
    let domain = ess_file("domains/babelforce-v1.yaml");
    let declared = domain
        .lines()
        .filter_map(|line| line.strip_prefix(&format!("  - name: {DOMAIN}.")))
        .collect::<Vec<_>>();
    let schemas = manifest["schemas"].as_object().unwrap();
    assert_eq!(declared.len(), schemas.len() + 3);
    assert_eq!(&declared[..3], ["Role", "Method", "Event"]);
    for name in schemas.keys() {
        assert!(declared.contains(&name.as_str()), "missing type {name}");
    }
    assert_eq!(declared.len(), 33);
}

#[test]
fn dotted_wire_names_become_pascal_case_variants_that_keep_the_wire_spelling() {
    assert_eq!(
        ess_variant("application.move").unwrap(),
        "name: ApplicationMove, wire: application.move"
    );
    assert_eq!(
        ess_variant("audio.buffer.clear").unwrap(),
        "name: AudioBufferClear, wire: audio.buffer.clear"
    );
    assert_eq!(ess_variant("ping").unwrap(), "name: ping");
    assert_eq!(
        ess_variant("output.transcript2.delta").unwrap(),
        "name: OutputTranscript2Delta, wire: output.transcript2.delta"
    );
    let domain = ess_file("domains/babelforce-v1.yaml");
    assert!(domain.contains(
        "      - {name: ApplicationMove, wire: application.move, attributes: {handled_by: voice, terminal: true,"
    ));
    assert!(domain.contains("      - {name: ping, attributes: {handled_by: both,"));
    let variant_lines = domain
        .lines()
        .filter(|line| line.starts_with("      - {name: "));
    for line in variant_lines {
        let name = line["      - {name: ".len()..]
            .split([',', '}'])
            .next()
            .unwrap();
        assert!(!name.contains('.'), "dotted variant name in {line}");
    }
}

#[test]
fn the_projection_maps_presence_bounds_and_nullability_as_the_rules_banner_says() {
    let text = render_ess_domain(
        &minimal_manifest(json!({
            "type": "object",
            "description": "A thing.",
            "required": ["count", "label", "parent"],
            "properties": {
                "count": {"type": "integer", "minimum": 1, "x-rtvbp-nonzero": true},
                "label": {"type": "string", "minLength": 2, "description": "Its label."},
                "parent": {
                    "anyOf": [{"$ref": "#/schemas/Thing"}, {"type": "null"}],
                    "x-rtvbp-presence": "nullable"
                },
                "score": {"type": "number", "format": "double"},
                "tags": {"type": "array", "items": {"type": "string"}},
                "extra": {"type": "object", "additionalProperties": true},
                "anything": {}
            },
            "x-rtvbp-field-order": [{"lower": "count", "upper": "count"}]
        })),
        "rtvbp.test_v1",
    )
    .unwrap();
    let expected = "  - name: rtvbp.test_v1.Thing
    kind: struct
    undeclared_fields: ignored
    naming: {summary: \"A thing.\"}
    fields:
      - name: count
        type: Integer
      - name: label
        type: String
        summary: \"Its label.\"
      - name: parent
        type: Optional<rtvbp.test_v1.Thing>
        presence: null_when_absent
      - name: score
        type: Optional<Json>
      - name: tags
        type: Optional<List<String>>
        presence: omitted_when_absent
      - name: extra
        type: Optional<Map<String, Json>>
        presence: omitted_when_absent
      - name: anything
        type: Optional<Json>
    invariants:
      - \"count >= 1\"
      - \"count != 0\"
      - \"label.count >= 2\"
      - \"count <= count\"
";
    assert!(text.ends_with(expected), "{text}");
    assert!(text.contains(
        "      - {name: ThingDo, wire: thing.do, attributes: {handled_by: voice, terminal: false, request: Thing, response: Thing}}"
    ));
}

