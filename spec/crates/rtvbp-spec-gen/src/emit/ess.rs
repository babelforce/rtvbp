//! The ESS projection of a catalog: one domain whose types are the catalog's schemas under their
//! catalog names, plus the operation and event names as two enums spelled as on the wire.
//!
//! The emitter reads the catalog manifest (the same document `--emit=manifest` writes), so the ESS
//! domain is a function of exactly the bytes other consumers see. A schema construct without a
//! rule here stops generation with its JSON path: the emitter never guesses a type.

use std::path::PathBuf;

use serde_json::{Map, Value};
use thiserror::Error;

use super::{GeneratedFile, Manifest};
use crate::resolve::ResolvedCatalog;

/// The ESS release the emitted specification is validated with.
pub const ESS_REQUIREMENT: &str = "ess 0.68.0";

/// The catalogs projected into the published ESS specification.
pub const ESS_CATALOGS: [&str; 1] = ["babelforce.v1"];

const SYSTEM: &str = "rtvbp";
const COMPONENT: &str = "protocol";
const OPEN_MAP: &str = "Map<String, Json>";
const SCHEMA_PREFIX: &str = "#/schemas/";
const ROLES: [&str; 3] = ["application", "voice", "both"];

/// Keys that only carry documentation or another SDK's spelling; each is named in the banner.
const IGNORED_KEYS: [&str; 3] = ["description", "format", "x-go-type"];

#[derive(Debug, Error)]
pub enum EssEmitError {
    #[error("ESS projection refused: {0}")]
    Refused(String),
    #[error("could not build the catalog manifest for ESS: {0}")]
    Json(#[from] serde_json::Error),
}

fn refuse(message: impl Into<String>) -> EssEmitError {
    EssEmitError::Refused(message.into())
}

/// Plain scalars a YAML 1.1 or 1.2 reader resolves to null or a boolean. An identifier the
/// emitter writes unquoted must not be one of them, in any letter case.
const YAML_RESERVED: [&str; 9] = ["null", "true", "false", "yes", "no", "on", "off", "y", "n"];

fn yaml_reserved(word: &str) -> bool {
    YAML_RESERVED.contains(&word.to_ascii_lowercase().as_str())
}

/// A field name, written as an unquoted YAML scalar: it must match `[A-Za-z_][A-Za-z0-9_]*` and
/// must not read as null or a boolean.
fn checked_field_name<'a>(name: &'a str, path: &str) -> Result<&'a str, EssEmitError> {
    let mut chars = name.chars();
    let identifier = chars
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
    if !identifier {
        return Err(refuse(format!(
            "{path}: field name {name:?} is not an identifier ([A-Za-z_][A-Za-z0-9_]*)"
        )));
    }
    if yaml_reserved(name) {
        return Err(refuse(format!(
            "{path}: field name {name:?} reads as a YAML null or boolean"
        )));
    }
    Ok(name)
}

/// Text written after `#` on one comment line: a line break would end the comment and the rest
/// would be read as YAML.
fn comment_text(value: &Value, what: &str) -> Result<String, EssEmitError> {
    let text = display(value);
    if text.contains(['\n', '\r']) {
        return Err(refuse(format!(
            "{what}: {text:?} contains a line break and cannot go into a comment"
        )));
    }
    Ok(text)
}

/// The ESS domain name of a catalog: `babelforce.v1` is `rtvbp.babelforce_v1`.
#[must_use]
pub fn ess_domain(catalog_id: &str) -> String {
    format!("{SYSTEM}.{}", catalog_id.replace('.', "_"))
}

/// The domain file of a catalog, relative to the specification root.
#[must_use]
pub fn ess_domain_path(catalog_id: &str) -> PathBuf {
    PathBuf::from("domains").join(format!("{}.yaml", catalog_id.replace('.', "-")))
}

/// Emit the domain file of one catalog.
pub fn emit_ess(catalog: &ResolvedCatalog) -> Result<Vec<GeneratedFile>, EssEmitError> {
    let manifest = serde_json::to_value(Manifest::from(catalog))?;
    let catalog_id = catalog.id.to_string();
    let text = render_domain(&manifest, &ess_domain(&catalog_id))?;
    Ok(vec![GeneratedFile {
        path: ess_domain_path(&catalog_id),
        bytes: text.into_bytes(),
    }])
}

/// Emit `system.yaml`, `components.yaml` and `ess-inputs.yaml` over the given catalogs.
#[must_use]
pub fn emit_ess_system(catalog_ids: &[String]) -> Vec<GeneratedFile> {
    let domains = catalog_ids
        .iter()
        .map(|id| ess_domain(id))
        .collect::<Vec<_>>();
    let mut system = vec![
        "format: ess/29".to_owned(),
        format!("system: {SYSTEM}"),
        "version: v1".to_owned(),
        "summary: >-".to_owned(),
        "  The RTVBP protocol catalogs as an ESS system, generated by rtvbp-spec-gen from the typed"
            .to_owned(),
        "  catalog (DO NOT EDIT; regenerate with `task generate`). One domain per catalog, owned by"
            .to_owned(),
        "  the protocol component, so a consumer can check its own copy of the wire types against"
            .to_owned(),
        "  this specification with `ess specify compose`.".to_owned(),
        "domains:".to_owned(),
    ];
    system.extend(domains.iter().map(|domain| format!("  - {domain}")));
    let components = vec![
        "components:".to_owned(),
        format!("  - component: {COMPONENT}"),
        "    owns:".to_owned(),
        format!("      domains: [{}]", domains.join(", ")),
        "    reached_by: in_process".to_owned(),
    ];
    let mut inputs = vec![
        "format: ess-inputs/2".to_owned(),
        format!("requires: {ESS_REQUIREMENT}"),
        String::new(),
        "specification:".to_owned(),
        "  - system.yaml".to_owned(),
        "  - components.yaml".to_owned(),
    ];
    inputs.extend(catalog_ids.iter().map(|id| {
        format!(
            "  - {}",
            ess_domain_path(id).to_string_lossy().replace('\\', "/")
        )
    }));
    inputs.push(String::new());
    inputs.push("scenarios: []".to_owned());
    [
        ("system.yaml", system),
        ("components.yaml", components),
        ("ess-inputs.yaml", inputs),
    ]
    .into_iter()
    .map(|(path, lines)| GeneratedFile {
        path: PathBuf::from(path),
        bytes: (lines.join("\n") + "\n").into_bytes(),
    })
    .collect()
}

fn q(text: &Value) -> String {
    match text {
        Value::String(_) => text.to_string(),
        other => Value::String(display(other)).to_string(),
    }
}

fn display(value: &Value) -> String {
    match value {
        Value::String(text) => text.clone(),
        other => other.to_string(),
    }
}

fn object<'a>(value: &'a Value, path: &str) -> Result<&'a Map<String, Value>, EssEmitError> {
    value
        .as_object()
        .ok_or_else(|| refuse(format!("{path}: not an object")))
}

fn field<'a>(value: &'a Value, key: &str, path: &str) -> Result<&'a Value, EssEmitError> {
    value
        .get(key)
        .ok_or_else(|| refuse(format!("{path}: missing {key:?}")))
}

fn text<'a>(value: &'a Value, key: &str, path: &str) -> Result<&'a str, EssEmitError> {
    field(value, key, path)?
        .as_str()
        .ok_or_else(|| refuse(format!("{path}: {key:?} is not a string")))
}

fn ref_name(domain: &str, reference: &Value, path: &str) -> Result<String, EssEmitError> {
    match reference
        .as_str()
        .and_then(|r| r.strip_prefix(SCHEMA_PREFIX))
    {
        Some(name) => Ok(format!("{domain}.{name}")),
        None => Err(refuse(format!("{path}: unsupported $ref {reference}"))),
    }
}

fn schema_name<'a>(reference: &'a Value, path: &str) -> Result<&'a str, EssEmitError> {
    field(reference, "$ref", path)?
        .as_str()
        .and_then(|r| r.strip_prefix(SCHEMA_PREFIX))
        .ok_or_else(|| refuse(format!("{path}: unsupported $ref")))
}

/// `number` (`format: double`) would be Binary64, which ESS 0.68.0 refuses in a conformance run
/// over the whole model; a Decimal is a JSON string on the wire, and the catalog sends a JSON
/// number. So it is `Json`, which keeps the wire value and loses only the "is a number" check; a
/// bound on such a field is refused.
fn scalar(kind: &str) -> Option<&'static str> {
    match kind {
        "string" => Some("String"),
        "integer" => Some("Integer"),
        "number" => Some("Json"),
        "boolean" => Some("Boolean"),
        _ => None,
    }
}

fn type_kinds(schema: &Value) -> Vec<Value> {
    match schema.get("type") {
        Some(Value::Array(kinds)) => kinds.clone(),
        Some(kind) => vec![kind.clone()],
        None => vec![Value::Null],
    }
}

/// The ESS type of a property schema, and whether the schema admits null.
fn value_type(domain: &str, schema: &Value, path: &str) -> Result<(String, bool), EssEmitError> {
    const KNOWN: [&str; 9] = [
        "$ref",
        "anyOf",
        "type",
        "items",
        "additionalProperties",
        "minLength",
        "minimum",
        "x-rtvbp-nonzero",
        "x-rtvbp-presence",
    ];
    let map = object(schema, path)?;
    for key in map.keys() {
        if !KNOWN.contains(&key.as_str()) && !IGNORED_KEYS.contains(&key.as_str()) {
            return Err(refuse(format!("{path}: no rule for key {key:?}")));
        }
    }
    if let Some(reference) = map.get("$ref") {
        return Ok((ref_name(domain, reference, path)?, false));
    }
    if let Some(options) = map.get("anyOf") {
        let options = options.as_array().map(Vec::as_slice).unwrap_or_default();
        let refs = options
            .iter()
            .filter(|o| o.get("$ref").is_some())
            .collect::<Vec<_>>();
        let null = serde_json::json!({"type": "null"});
        let nulls = options.iter().filter(|o| **o == null).count();
        if refs.len() == 1 && nulls == 1 && options.len() == 2 {
            return Ok((ref_name(domain, &refs[0]["$ref"], path)?, true));
        }
        return Err(refuse(format!("{path}: anyOf other than [$ref, null]")));
    }
    let Some(declared) = map.get("type") else {
        return Ok(("Json".to_owned(), false));
    };
    let kinds = type_kinds(schema);
    let nullable = kinds.iter().any(|k| k == "null");
    let kinds = kinds
        .into_iter()
        .filter(|k| k != "null")
        .collect::<Vec<_>>();
    if kinds.len() != 1 {
        return Err(refuse(format!("{path}: type {declared}")));
    }
    let kind = &kinds[0];
    if let Some(ess) = kind.as_str().and_then(scalar) {
        return Ok((ess.to_owned(), nullable));
    }
    if kind == "array" {
        let items = map
            .get("items")
            .ok_or_else(|| refuse(format!("{path}: array without items")))?;
        let (inner, inner_null) = value_type(domain, items, &format!("{path}/items"))?;
        if inner_null {
            return Err(refuse(format!("{path}/items: nullable items")));
        }
        return Ok((format!("List<{inner}>"), nullable));
    }
    if kind == "object" {
        if map.get("additionalProperties") == Some(&Value::Bool(true))
            && !map.contains_key("properties")
        {
            return Ok((OPEN_MAP.to_owned(), nullable));
        }
        return Err(refuse(format!("{path}: inline object with properties")));
    }
    Err(refuse(format!("{path}: type {kind}")))
}

fn field_rules(name: &str, schema: &Value) -> Vec<String> {
    let mut rules = Vec::new();
    if let Some(min) = schema.get("minLength") {
        rules.push(format!("{name}.count >= {min}"));
    }
    if let Some(min) = schema.get("minimum") {
        rules.push(format!("{name} >= {min}"));
    }
    if schema.get("x-rtvbp-nonzero") == Some(&Value::Bool(true)) {
        rules.push(format!("{name} != 0"));
    }
    rules
}

fn struct_lines(
    domain: &str,
    name: &str,
    schema: &Value,
    path: &str,
) -> Result<Vec<String>, EssEmitError> {
    const KNOWN: [&str; 6] = [
        "type",
        "properties",
        "required",
        "description",
        "additionalProperties",
        "x-rtvbp-field-order",
    ];
    let map = object(schema, path)?;
    for key in map.keys() {
        if !KNOWN.contains(&key.as_str()) {
            return Err(refuse(format!("{path}: no rule for key {key:?}")));
        }
    }
    let required = map
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect::<Vec<_>>())
        .unwrap_or_default();
    let empty = Map::new();
    let properties = map
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&empty);
    let mut missing = required
        .iter()
        .filter(|name| !properties.contains_key(**name))
        .collect::<Vec<_>>();
    if !missing.is_empty() {
        missing.sort();
        return Err(refuse(format!(
            "{path}: required but not declared: {missing:?}"
        )));
    }
    let mut lines = vec![
        format!("  - name: {domain}.{name}"),
        "    kind: struct".to_owned(),
        "    undeclared_fields: ignored".to_owned(),
    ];
    if let Some(description) = map.get("description") {
        lines.push(format!("    naming: {{summary: {}}}", q(description)));
    }
    lines.push("    fields:".to_owned());
    let mut invariants = Vec::new();
    for (field_name, prop) in properties {
        let fpath = format!("{path}/properties/{field_name}");
        let (mut ess_type, nullable) = value_type(domain, prop, &fpath)?;
        let is_required = required.contains(&field_name.as_str());
        let mut presence = None;
        if is_required {
            if nullable {
                if prop.get("x-rtvbp-presence").and_then(Value::as_str) != Some("nullable") {
                    return Err(refuse(format!(
                        "{fpath}: required and nullable without x-rtvbp-presence"
                    )));
                }
                ess_type = format!("Optional<{ess_type}>");
                presence = Some("null_when_absent");
            }
        } else {
            ess_type = format!("Optional<{ess_type}>");
            // An absent optional is omitted. `Optional<Json>` takes no presence: JSON null is one
            // of its values, so ESS refuses `omitted_when_absent` there.
            if !ess_type.starts_with("Optional<Json") {
                presence = Some("omitted_when_absent");
            }
        }
        lines.push(format!(
            "      - name: {}",
            checked_field_name(field_name, &fpath)?
        ));
        lines.push(format!("        type: {ess_type}"));
        if let Some(presence) = presence {
            lines.push(format!("        presence: {presence}"));
        }
        if let Some(description) = prop.get("description") {
            lines.push(format!("        summary: {}", q(description)));
        }
        for rule in field_rules(field_name, prop) {
            if type_kinds(prop).iter().any(|k| k == "number") {
                return Err(refuse(format!(
                    "{fpath}: a bound on a number, which is Json here"
                )));
            }
            if !is_required {
                return Err(refuse(format!("{fpath}: a bound on an optional field")));
            }
            invariants.push(rule);
        }
    }
    if let Some(pairs) = map.get("x-rtvbp-field-order") {
        let pairs = pairs
            .as_array()
            .ok_or_else(|| refuse(format!("{path}/x-rtvbp-field-order: not a list")))?;
        for pair in pairs {
            let lower = display(field(pair, "lower", path)?);
            let upper = display(field(pair, "upper", path)?);
            invariants.push(format!("{lower} <= {upper}"));
        }
    }
    if !invariants.is_empty() {
        lines.push("    invariants:".to_owned());
        lines.extend(
            invariants
                .iter()
                .map(|rule| format!("      - {}", q(&Value::String(rule.clone())))),
        );
    }
    Ok(lines)
}

fn type_lines(domain: &str, name: &str, schema: &Value) -> Result<Vec<String>, EssEmitError> {
    let path = format!("/schemas/{name}");
    let map = object(schema, &path)?;
    if map.get("type").and_then(Value::as_str) != Some("object") {
        return Err(refuse(format!(
            "{path}: a top-level schema that is not an object"
        )));
    }
    if map
        .get("properties")
        .and_then(Value::as_object)
        .is_some_and(|properties| !properties.is_empty())
    {
        return struct_lines(domain, name, schema, &path);
    }
    for key in map.keys() {
        if !["type", "description", "additionalProperties"].contains(&key.as_str()) {
            return Err(refuse(format!("{path}: no rule for key {key:?}")));
        }
    }
    if map
        .get("additionalProperties")
        .is_some_and(|open| *open != Value::Bool(true))
    {
        return Err(refuse(format!(
            "{path}: a closed object without properties"
        )));
    }
    // A JSON object with no declared member; ESS refuses a struct without fields, and the Rust SDK
    // holds these as a transparent `serde_json::Map`.
    let mut lines = vec![
        format!("  - name: {domain}.{name}"),
        "    kind: newtype".to_owned(),
        format!("    of: {OPEN_MAP}"),
    ];
    if let Some(description) = map.get("description") {
        lines.push(format!("    naming: {{summary: {}}}", q(description)));
    }
    Ok(lines)
}

/// The variant name a wire name maps to, and whether it needs a `wire:` spelling.
///
/// A dot is not allowed in a generated identifier (`ess generate synthesize` refuses
/// `Application.move`), so `application.move` becomes `ApplicationMove`; an undotted name such as
/// `ping` stays as it is. Only names whose dot-separated segments each match `[a-z][a-z0-9]*` have
/// a rule: anything else (`audio.buffer-clear`, `Session.set`, `a..b`) is refused, because the
/// mapping would yield a non-identifier or fold two wire names into one variant. An undotted name
/// that YAML reads as null or a boolean (`null`, `true`, `on`) is refused too: it is written
/// unquoted.
fn variant_name(wire: &str) -> Result<String, EssEmitError> {
    let segment_ok = |part: &str| {
        let mut chars = part.chars();
        chars.next().is_some_and(|first| first.is_ascii_lowercase())
            && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
    };
    if !wire.split('.').all(segment_ok) {
        return Err(refuse(format!(
            "wire name {wire:?}: no variant rule (each dot-separated segment must match [a-z][a-z0-9]*)"
        )));
    }
    if !wire.contains('.') {
        if yaml_reserved(wire) {
            return Err(refuse(format!(
                "wire name {wire:?}: no variant rule (it reads as a YAML null or boolean)"
            )));
        }
        return Ok(wire.to_owned());
    }
    Ok(wire
        .split('.')
        .map(|part| part[..1].to_ascii_uppercase() + &part[1..])
        .collect())
}

/// The enum variant for a wire name: `application.move` is
/// `name: ApplicationMove, wire: application.move`, and `ping` is `name: ping`.
pub fn variant(wire: &str) -> Result<String, EssEmitError> {
    let name = variant_name(wire)?;
    if name == wire {
        Ok(format!("name: {wire}"))
    } else {
        Ok(format!("name: {name}, wire: {wire}"))
    }
}

/// Refuse two wire names of one enum that map to the same variant name.
fn unique_variants<'a>(
    enum_name: &str,
    wires: impl IntoIterator<Item = &'a str>,
) -> Result<(), EssEmitError> {
    let mut seen = std::collections::BTreeMap::<String, &str>::new();
    for wire in wires {
        let name = variant_name(wire)?;
        if let Some(earlier) = seen.insert(name.clone(), wire) {
            return Err(refuse(format!(
                "{enum_name}: wire names {earlier:?} and {wire:?} both map to variant {name}"
            )));
        }
    }
    Ok(())
}

fn checked_role<'a>(item: &'a Value, key: &str, what: &str) -> Result<&'a str, EssEmitError> {
    let role = text(item, key, what)?;
    if ROLES.contains(&role) {
        Ok(role)
    } else {
        Err(refuse(format!("{what}: {key} {role:?}")))
    }
}

fn list<'a>(manifest: &'a Value, key: &str) -> Result<&'a [Value], EssEmitError> {
    field(manifest, key, "/")?
        .as_array()
        .map(Vec::as_slice)
        .ok_or_else(|| refuse(format!("/{key}: not a list")))
}

/// Render the ESS domain of a catalog manifest under the given domain name.
pub fn render_domain(manifest: &Value, domain: &str) -> Result<String, EssEmitError> {
    if manifest.get("formatVersion") != Some(&Value::from(1)) {
        return Err(refuse(format!(
            "formatVersion {}",
            manifest.get("formatVersion").unwrap_or(&Value::Null)
        )));
    }
    let ident = text(field(manifest, "catalog", "/")?, "id", "/catalog")?;
    let schemas = object(field(manifest, "schemas", "/")?, "/schemas")?;
    let operations = list(manifest, "operations")?;
    let events = list(manifest, "events")?;
    let mut out = vec![
        "# Code generated by rtvbp-spec-gen from the typed catalog. DO NOT EDIT.".to_owned(),
        "# Regenerate with `task generate` (`rtvbp-spec-gen --emit=ess`).".to_owned(),
        format!("# Source: catalog {ident}, as `--emit=manifest` writes it."),
        "# Rules: a schema with properties is a struct that ignores undeclared members (the catalog"
            .to_owned(),
        "# never closes an object); an object with none is `Map<String, Json>`; integer is Integer,"
            .to_owned(),
        "# number is Json (Binary64 fails every ESS 0.68.0 conformance run and Decimal is a JSON"
            .to_owned(),
        "# string on the wire, see spec/crates/rtvbp-spec-gen/src/emit/ess.rs); a".to_owned(),
        "# property outside `required` is Optional and omitted when absent (`Optional<Json>` takes no"
            .to_owned(),
        "# presence, since JSON null is one of its values); a required nullable property".to_owned(),
        "# (`x-rtvbp-presence: nullable`) is Optional and sent as null;".to_owned(),
        "# `minLength`, `minimum`, `x-rtvbp-nonzero` and `x-rtvbp-field-order` are invariants."
            .to_owned(),
        "# Not carried: `format` (int64, double), `x-go-type` and the per-operation `examples`."
            .to_owned(),
        format!("domain: {domain}"),
        String::new(),
        "summary: >-".to_owned(),
        format!(
            "  The `{ident}` RTVBP catalog as typed by the protocol repository: every payload schema"
        ),
        "  under its catalog name, and the operation and event names as the wire spells them. What"
            .to_owned(),
        "  the AI Agent Platform does with them is `aap.rtvbp`.".to_owned(),
        String::new(),
        "naming:".to_owned(),
        "  wire: rtvbp-wire".to_owned(),
        "  display: RTVBP wire catalog".to_owned(),
        String::new(),
        "types:".to_owned(),
        "  # The role that handles an operation or emits an event (`handledBy`, `emittedBy`)."
            .to_owned(),
        format!("  - name: {domain}.Role"),
        "    kind: enum".to_owned(),
        "    variants: [application, voice, both]".to_owned(),
        String::new(),
        "  # The catalog's operations: who handles each, whether the session ends after the reply,"
            .to_owned(),
        "  # and the request and response schema.".to_owned(),
    ];
    for op in operations {
        let method = text(op, "method", "/operations")?;
        let what = format!("operation {method}");
        checked_role(op, "handledBy", &what)?;
        out.push(format!(
            "  #   {method}: {}",
            comment_text(field(op, "description", &what)?, &what)?
        ));
        if let Some(rejections) = op.get("rejections").and_then(Value::as_array) {
            for rej in rejections {
                out.push(format!(
                    "  #     rejected by the {} role with {} {}",
                    comment_text(field(rej, "role", &what)?, &what)?,
                    comment_text(field(rej, "code", &what)?, &what)?,
                    q(field(rej, "message", &what)?)
                ));
            }
        }
    }
    out.extend([
        format!("  - name: {domain}.Method"),
        "    kind: enum".to_owned(),
        "    attributes:".to_owned(),
        format!("      - {{name: handled_by, type: {domain}.Role}}"),
        "      - {name: terminal, type: Boolean}".to_owned(),
        "      - {name: request, type: String}".to_owned(),
        "      - {name: response, type: String}".to_owned(),
        "    variants:".to_owned(),
    ]);
    unique_variants(
        "Method",
        operations
            .iter()
            .map(|op| text(op, "method", "/operations"))
            .collect::<Result<Vec<_>, _>>()?,
    )?;
    for op in operations {
        let method = text(op, "method", "/operations")?;
        let what = format!("operation {method}");
        let request = schema_name(field(op, "request", &what)?, &what)?;
        let response = schema_name(field(op, "response", &what)?, &what)?;
        for (side, name) in [("request", request), ("response", response)] {
            if !schemas.contains_key(name) {
                return Err(refuse(format!("{what}: unknown {side} schema")));
            }
        }
        let terminal = field(op, "terminal", &what)?
            .as_bool()
            .ok_or_else(|| refuse(format!("{what}: terminal is not a boolean")))?;
        out.push(format!(
            "      - {{{}, attributes: {{handled_by: {}, terminal: {terminal}, request: {request}, response: {response}}}}}",
            variant(method)?,
            checked_role(op, "handledBy", &what)?
        ));
    }
    out.push(String::new());
    out.push("  # The catalog's events: who emits each, and its data schema.".to_owned());
    for ev in events {
        let name = text(ev, "name", "/events")?;
        let what = format!("event {name}");
        checked_role(ev, "emittedBy", &what)?;
        out.push(format!(
            "  #   {name}: {}",
            comment_text(field(ev, "description", &what)?, &what)?
        ));
    }
    out.extend([
        format!("  - name: {domain}.Event"),
        "    kind: enum".to_owned(),
        "    attributes:".to_owned(),
        format!("      - {{name: emitted_by, type: {domain}.Role}}"),
        "      - {name: data, type: String}".to_owned(),
        "    variants:".to_owned(),
    ]);
    unique_variants(
        "Event",
        events
            .iter()
            .map(|ev| text(ev, "name", "/events"))
            .collect::<Result<Vec<_>, _>>()?,
    )?;
    for ev in events {
        let name = text(ev, "name", "/events")?;
        let what = format!("event {name}");
        let data = schema_name(field(ev, "data", &what)?, &what)?;
        if !schemas.contains_key(data) {
            return Err(refuse(format!("{what}: unknown data schema")));
        }
        out.push(format!(
            "      - {{{}, attributes: {{emitted_by: {}, data: {data}}}}}",
            variant(name)?,
            checked_role(ev, "emittedBy", &what)?
        ));
    }
    for (name, schema) in schemas {
        out.push(String::new());
        out.extend(type_lines(domain, name, schema)?);
    }
    Ok(out.join("\n") + "\n")
}
